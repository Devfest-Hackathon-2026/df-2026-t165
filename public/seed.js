/** 最初の起動で一度だけ入れる。入れたかどうかは state.seed に残し、消しても勝手に戻さない */
export function seedDemo(state){
 if(state.seed===SEED_ID)return false;
 const have=new Set(state.requests.map(r=>r.id)),add=SEED_REQUESTS.filter(r=>!have.has(r.id));
 state.requests.push(...structuredClone(add));state.seed=SEED_ID;
 return add.length>0;
}
